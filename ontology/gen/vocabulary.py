"""Generate the store vocabulary, the Go vocabulary and a JSON vocabulary from the Context Model.

LinkML's own SQL generator makes one table per class. The store does not work that way: it has one
entity table and one edge table, and kinds are data. This generator writes what the store and the Go
code need instead:

  generated/sql/vocabulary.sql   kind and relation tables, their rows, and the domain/range check on edges
  generated/go/vocab/vocab.go    entity kinds, relation kinds, attributes and enums as Go values
  generated/ts/vocabulary.ts     entity kinds and relation kinds as TypeScript union types (the web UI)
  generated/vocabulary.json      the same, for any other consumer

Run through `make ontology`; never edit the output by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from linkml_runtime.utils.schemaview import SchemaView

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "generated"

TYPE_MAP = {
    "string": "string",
    "integer": "integer",
    "boolean": "boolean",
    "datetime": "datetime",
    "date": "date",
    "uri": "uri",
    "float": "number",
}


def load() -> dict:
    sv = SchemaView(str(ROOT / "context_model.yaml"))
    enums = {
        name: [str(v) for v in e.permissible_values.keys()]
        for name, e in sorted(sv.all_enums().items())
    }
    relations = []
    for name, slot in sorted(sv.all_slots().items()):
        ann = {k: v.value for k, v in (slot.annotations or {}).items()}
        if "ctx_domain" not in ann:
            continue
        relations.append(
            {
                "kind": name,
                "description": slot.description or "",
                "domain": str(ann["ctx_domain"]).split(),
                "range": str(ann["ctx_range"]).split(),
                "cardinality": str(ann.get("ctx_cardinality", "many")),
            }
        )
    relation_names = {r["kind"] for r in relations}
    kinds = []
    for name, cls in sv.all_classes().items():
        if cls.abstract:
            continue
        ann = {k: v.value for k, v in (cls.annotations or {}).items()}
        attrs = []
        for slot in sv.class_induced_slots(name):
            if slot.name in relation_names or slot.name in ("id", "name", "standing", "last_seen"):
                continue
            rng = slot.range or "string"
            attr = {"name": slot.name, "description": slot.description or ""}
            if rng in enums:
                attr["type"] = "enum"
                attr["enum"] = rng
            else:
                attr["type"] = TYPE_MAP.get(rng, "string")
            attrs.append(attr)
        kinds.append(
            {
                "kind": name,
                "description": (cls.description or "").strip(),
                "id_pattern": str(ann.get("ctx_id_pattern", "{name}")),
                "attributes": sorted(attrs, key=lambda a: a["name"]),
            }
        )
    kinds.sort(key=lambda k: k["kind"])
    kind_names = {k["kind"] for k in kinds}
    for r in relations:
        for side in ("domain", "range"):
            if r[side] == ["Entity"]:
                r[side] = sorted(kind_names)
            unknown = set(r[side]) - kind_names
            if unknown:
                sys.exit(f"relation {r['kind']}: unknown {side} kinds {sorted(unknown)}")
    return {
        "version": str(sv.schema.version),
        "kinds": kinds,
        "relations": relations,
        "enums": enums,
    }


def sql_str(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def write_sql(v: dict) -> str:
    out = [
        "-- Generated by ontology/gen/vocabulary.py from ontology/context_model.yaml. Do not edit.",
        f"-- Context Model version {v['version']}",
        "",
        "create table if not exists entity_kind (",
        "  kind        text primary key,",
        "  description text not null",
        ");",
        "create table if not exists relation_kind (",
        "  kind        text primary key,",
        "  cardinality text not null check (cardinality in ('one', 'many')),",
        "  description text not null",
        ");",
        "create table if not exists relation_domain (",
        "  relation text not null references relation_kind(kind),",
        "  kind     text not null references entity_kind(kind),",
        "  primary key (relation, kind)",
        ");",
        "create table if not exists relation_range (",
        "  relation text not null references relation_kind(kind),",
        "  kind     text not null references entity_kind(kind),",
        "  primary key (relation, kind)",
        ");",
        "",
        "delete from relation_domain; delete from relation_range;",
        "delete from relation_kind where kind not in ("
        + ", ".join(sql_str(r["kind"]) for r in v["relations"])
        + ");",
        "",
    ]
    for k in v["kinds"]:
        out.append(
            "insert into entity_kind values (%s, %s) on conflict (kind) do update set description = excluded.description;"
            % (sql_str(k["kind"]), sql_str(k["description"]))
        )
    out.append("")
    for r in v["relations"]:
        out.append(
            "insert into relation_kind values (%s, %s, %s) on conflict (kind) do update set cardinality = excluded.cardinality, description = excluded.description;"
            % (sql_str(r["kind"]), sql_str(r["cardinality"]), sql_str(r["description"]))
        )
        for d in r["domain"]:
            out.append("insert into relation_domain values (%s, %s);" % (sql_str(r["kind"]), sql_str(d)))
        for g in r["range"]:
            out.append("insert into relation_range values (%s, %s);" % (sql_str(r["kind"]), sql_str(g)))
    out += [
        "",
        "-- Every edge must respect its relation's domain and range.",
        "create or replace function edge_check_vocabulary() returns trigger language plpgsql as $$",
        "declare from_kind text; to_kind text;",
        "begin",
        "  select kind into from_kind from entity where id = new.from_id;",
        "  select kind into to_kind from entity where id = new.to_id;",
        "  if not exists (select 1 from relation_domain where relation = new.kind and kind = from_kind) then",
        "    raise exception 'edge %: % may not start from %', new.id, new.kind, from_kind;",
        "  end if;",
        "  if not exists (select 1 from relation_range where relation = new.kind and kind = to_kind) then",
        "    raise exception 'edge %: % may not point to %', new.id, new.kind, to_kind;",
        "  end if;",
        "  return new;",
        "end $$;",
        "",
    ]
    return "\n".join(out)


def go_ident(s: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in s.replace("-", "_").split("_"))


def write_go(v: dict) -> str:
    q = json.dumps
    out = [
        "// Code generated by ontology/gen/vocabulary.py from ontology/context_model.yaml. DO NOT EDIT.",
        "",
        "// Package vocab holds the Context Model's entity kinds, relation kinds, attributes and enums.",
        "package vocab",
        "",
        f"// Version is the Context Model version these values were generated from.",
        f"const Version = {q(v['version'])}",
        "",
        "// Entity kinds.",
        "const (",
    ]
    for k in v["kinds"]:
        out.append(f"\t{k['kind']} = {q(k['kind'])}")
    out += [")", "", "// Relation kinds.", "const ("]
    for r in v["relations"]:
        out.append(f"\t{go_ident(r['kind'])} = {q(r['kind'])}")
    out += [")", ""]
    out += [
        "// Attribute describes one attribute of an entity kind.",
        "type Attribute struct {",
        "\tName        string",
        "\tType        string // string, integer, boolean, datetime, date, uri, number, enum",
        "\tEnum        string",
        "\tDescription string",
        "}",
        "",
        "// Kind describes one entity kind.",
        "type Kind struct {",
        "\tName        string",
        "\tDescription string",
        "\tIDPattern   string",
        "\tAttributes  []Attribute",
        "}",
        "",
        "// Relation describes one relation kind.",
        "type Relation struct {",
        "\tName        string",
        "\tDescription string",
        "\tDomain      []string",
        "\tRange       []string",
        "\tCardinality string // one or many",
        "}",
        "",
        "// Kinds lists every entity kind, sorted by name.",
        "var Kinds = []Kind{",
    ]
    for k in v["kinds"]:
        out.append(f"\t{{Name: {q(k['kind'])}, Description: {q(k['description'])}, IDPattern: {q(k['id_pattern'])}, Attributes: []Attribute{{")
        for a in k["attributes"]:
            out.append(
                f"\t\t{{Name: {q(a['name'])}, Type: {q(a['type'])}, Enum: {q(a.get('enum', ''))}, Description: {q(a['description'])}}},"
            )
        out.append("\t}},")
    out += ["}", "", "// Relations lists every relation kind, sorted by name.", "var Relations = []Relation{"]
    for r in v["relations"]:
        dom = ", ".join(q(d) for d in r["domain"])
        rng = ", ".join(q(d) for d in r["range"])
        out.append(
            f"\t{{Name: {q(r['kind'])}, Description: {q(r['description'])}, Domain: []string{{{dom}}}, Range: []string{{{rng}}}, Cardinality: {q(r['cardinality'])}}},"
        )
    out += ["}", "", "// Enums maps each enum name to its permissible values.", "var Enums = map[string][]string{"]
    for name, values in v["enums"].items():
        out.append(f"\t{q(name)}: {{{', '.join(q(x) for x in values)}}},")
    out += ["}", ""]
    return "\n".join(out)


def write_ts(v: dict) -> str:
    q = json.dumps
    out = [
        "// Generated by ontology/gen/vocabulary.py from ontology/context_model.yaml. Do not edit.",
        f"export const VERSION = {q(v['version'])};",
        "",
        "export const KINDS = [" + ", ".join(q(k["kind"]) for k in v["kinds"]) + "] as const;",
        "export type Kind = (typeof KINDS)[number];",
        "",
        "export const RELATIONS = [" + ", ".join(q(r["kind"]) for r in v["relations"]) + "] as const;",
        "export type Relation = (typeof RELATIONS)[number];",
        "",
        "export const KIND_DESCRIPTIONS: Record<Kind, string> = {",
    ]
    out += [f"  {k['kind']}: {q(k['description'])}," for k in v["kinds"]]
    out += ["};", "", "export const RELATION_INFO: Record<Relation, { description: string; domain: Kind[]; range: Kind[]; cardinality: \"one\" | \"many\" }> = {"]
    for r in v["relations"]:
        out.append(f"  {r['kind']}: {{ description: {q(r['description'])}, domain: {q(r['domain'])}, range: {q(r['range'])}, cardinality: {q(r['cardinality'])} }},")
    out += ["};", ""]
    return "\n".join(out)


def main() -> None:
    v = load()
    (OUT / "sql").mkdir(parents=True, exist_ok=True)
    (OUT / "go" / "vocab").mkdir(parents=True, exist_ok=True)
    (OUT / "sql" / "vocabulary.sql").write_text(write_sql(v))
    (OUT / "go" / "vocab" / "vocab.go").write_text(write_go(v))
    (OUT / "ts").mkdir(parents=True, exist_ok=True)
    (OUT / "ts" / "vocabulary.ts").write_text(write_ts(v))
    (OUT / "vocabulary.json").write_text(json.dumps(v, indent=2) + "\n")
    print(f"vocabulary: {len(v['kinds'])} kinds, {len(v['relations'])} relations")


if __name__ == "__main__":
    main()
